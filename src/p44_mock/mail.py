"""Simulazione della mail di invito che P44 invia al vettore: file .eml su disco."""

import os
import re
from email.message import EmailMessage
from email.utils import format_datetime

MITTENTE_P44 = "project44 (mock) <no-reply@project44.mock>"

_TESTI = {
    "it": ("Invito a collegarsi con {inv} su project44",
           "Gentile {nome},\n\n{inv} la invita a condividere il tracciamento dei mezzi "
           "({cap}) tramite project44.\nPer accettare, acceda al link ricevuto da project44 "
           "e completi la registrazione.\n\nQuesta è una mail simulata dal mock P44 (POC FERCAM).\n"),
    "en": ("{inv} invites you to connect on project44",
           "Dear {nome},\n\n{inv} invites you to share asset tracking ({cap}) via project44.\n"
           "To accept, follow the link sent by project44 and complete the registration.\n\n"
           "This is a simulated e-mail generated by the P44 mock (FERCAM POC).\n"),
}


def scrivi_mail_invito(cartella: str, invito: dict, invitante: str, istante) -> list:
    """Scrive un .eml per ogni contatto dell'invitee. Restituisce i percorsi creati."""
    if not cartella:
        return []
    os.makedirs(cartella, exist_ok=True)
    creati = []
    invitee = invito["invitee"]
    ident = invitee["identifiers"][0]
    for n, contatto in enumerate(invitee.get("contacts", []), start=1):
        lingua = "it" if contatto.get("locale", "en-US").startswith("it") else "en"
        oggetto, corpo = _TESTI[lingua]
        msg = EmailMessage()
        msg["From"] = MITTENTE_P44
        msg["To"] = contatto["email"]
        msg["Date"] = format_datetime(istante)
        msg["Subject"] = oggetto.format(inv=invitante)
        msg["X-P44-Mock-Capability"] = invito["capability"]
        msg.set_content(corpo.format(inv=invitante, nome=contatto.get("givenName", ""),
                                     cap=invito["capability"]))
        # Nome file sicuro: timestamp virtuale + identificativo
        valore = re.sub(r"[^A-Za-z0-9_-]", "_", ident["value"])
        nome = f"{istante.strftime('%Y%m%dT%H%M%S')}_invito_{ident['type']}_{valore}_{n}.eml"
        percorso = os.path.join(cartella, nome)
        with open(percorso, "wb") as f:
            f.write(bytes(msg))
        creati.append(percorso)
    return creati
